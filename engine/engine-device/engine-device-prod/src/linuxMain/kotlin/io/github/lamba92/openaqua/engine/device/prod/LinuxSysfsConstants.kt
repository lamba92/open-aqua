package io.github.lamba92.openaqua.engine.device.prod

/*
 * Linux sysfs and HID subsystem constants and path builders.
 */

// -----------------------------------------------------------------------------
// HID (Human Interface Device) & Sysfs Device Tree
// -----------------------------------------------------------------------------

/**
 * Base directory in sysfs where all registered HID raw devices are exposed.
 * Each entry inside (e.g. `hidraw0`, `hidraw9`) corresponds to a connected USB/HID endpoint.
 */
internal const val SYSFS_HIDRAW_DIR = "/sys/class/hidraw"

/**
 * Linux device node directory containing character device files (e.g. `/dev/hidraw9`)
 * used for userspace read, write, and ioctl operations.
 */
internal const val DEV_DIR = "/dev"

/**
 * Relative path from `/sys/class/hidraw/<entry>/` to its kernel `uevent` file.
 * The kernel writes key-value pairs here describing the device, such as `HID_ID` and `HID_UNIQ`.
 */
internal const val DEVICE_UEVENT = "device/uevent"

/**
 * The `uevent` key prefix for the HID bus, vendor, and product IDs.
 * Format generated by the Linux kernel: `HID_ID=<bus>:<vendorId_hex>:<productId_hex>`.
 * Example: `HID_ID=0003:00000C70:0000F011`.
 */
internal const val UEVENT_HID_ID_PREFIX = "HID_ID="

/**
 * The `uevent` key prefix for the device unique serial number string.
 * For Aquacomputer USB devices, this contains the factory serial number (e.g. `10000-00001`).
 */
internal const val UEVENT_HID_UNIQ_PREFIX = "HID_UNIQ="

/**
 * Delimiter used in the kernel's `HID_ID` string to separate bus, vendor, and product IDs.
 */
internal const val UEVENT_DELIMITER = ":"

// -----------------------------------------------------------------------------
// HID Status Report & Protocol Constants
// -----------------------------------------------------------------------------

/**
 * Default timeout in milliseconds when polling for an incoming status report.
 */
internal const val DEFAULT_HID_REPORT_TIMEOUT_MS = 1200

// -----------------------------------------------------------------------------
// Linux ioctl command builder for HIDIOCSFEATURE (Set Feature Report)
// -----------------------------------------------------------------------------

/**
 * Encodes `_IOC(_IOC_WRITE|_IOC_READ, 'H', 0x06, length)` matching the kernel
 * definition in `<linux/hidraw.h>`.
 *
 * `HIDIOCSFEATURE(len)` opcode:
 * - Direction: `_IOC_READ | _IOC_WRITE` (bits 30..31 = 0x3)
 * - Size: length in bytes (bits 16..29)
 * - Type: `'H'` = 0x48 (bits 8..15)
 * - Number: 0x06 (bits 0..7)
 *
 * @param length Total feature report buffer size in bytes (Report ID byte + payload).
 */
internal fun hidiocsfeature(length: Int): ULong {
    val dir = 3UL shl 30
    val size = (length.toULong() and 0x3FFFUL) shl 16
    val type = 'H'.code.toULong() shl 8
    val nr = 0x06UL
    return dir or size or type or nr
}

// -----------------------------------------------------------------------------
// Sysfs Path Builders
// -----------------------------------------------------------------------------

/**
 * Builds the absolute sysfs path to the `uevent` file for a given hidraw device node.
 * Example: `hidraw9` -> `/sys/class/hidraw/hidraw9/device/uevent`.
 */
internal fun hidrawUeventPath(hidrawName: String): String = "$SYSFS_HIDRAW_DIR/$hidrawName/$DEVICE_UEVENT"

/**
 * Builds the character device path under `/dev` for a given hidraw device node.
 * Example: `hidraw9` -> `/dev/hidraw9`.
 */
internal fun hidrawDevPath(hidrawName: String): String = "$DEV_DIR/$hidrawName"

package com.openaqua.engine.prod

/**
 * Linux sysfs and hwmon subsystem constants and path builders.
 *
 * In Linux, the `/sys` filesystem (sysfs) is a pseudo-filesystem provided by the Linux kernel
 * that exports device drivers, buses, and hardware monitoring attributes to userspace.
 */

// -----------------------------------------------------------------------------
// HID (Human Interface Device) & Sysfs Device Tree
// -----------------------------------------------------------------------------

/**
 * Base directory in sysfs where all registered HID raw devices are exposed.
 * Each entry inside (e.g. `hidraw0`, `hidraw9`) corresponds to a connected USB/HID endpoint.
 */
internal const val SYSFS_HIDRAW_DIR = "/sys/class/hidraw"

/**
 * Linux device node directory containing character device files (e.g. `/dev/hidraw9`)
 * used for userspace read, write, and ioctl operations.
 */
internal const val DEV_DIR = "/dev"

/**
 * Relative path from `/sys/class/hidraw/<entry>/` to its kernel `uevent` file.
 * The kernel writes key-value pairs here describing the device, such as `HID_ID` and `HID_UNIQ`.
 */
internal const val DEVICE_UEVENT = "device/uevent"

/**
 * Relative path from `/sys/class/hidraw/<entry>/` to its associated hardware monitoring subdirectory.
 * When the `aquacomputer_d5next` kernel driver is loaded, it registers a hwmon device under this directory.
 */
internal const val DEVICE_HWMON = "device/hwmon"

/**
 * Prefix of the hwmon instance directory created by the kernel (e.g. `hwmon3`).
 * The full path is typically `/sys/class/hidraw/<entry>/device/hwmon/hwmonX`.
 */
internal const val HWMON_PREFIX = "hwmon"

/**
 * The `uevent` key prefix for the HID bus, vendor, and product IDs.
 * Format generated by the Linux kernel: `HID_ID=<bus>:<vendorId_hex>:<productId_hex>`.
 * Example: `HID_ID=0003:00000C70:0000F001`.
 */
internal const val UEVENT_HID_ID_PREFIX = "HID_ID="

/**
 * The `uevent` key prefix for the device unique serial number string.
 * For Aquacomputer USB devices, this contains the factory serial number (e.g. `13235-54067`).
 */
internal const val UEVENT_HID_UNIQ_PREFIX = "HID_UNIQ="

/**
 * Delimiter used in the kernel's `HID_ID` string to separate bus, vendor, and product IDs.
 */
internal const val UEVENT_DELIMITER = ":"

// -----------------------------------------------------------------------------
// Linux hwmon (Hardware Monitoring) Subsystem Standard Attribute Names
//
// Documented by the Linux kernel ABI: Documentation/hwmon/sysfs-interface.rst
// -----------------------------------------------------------------------------

/**
 * Standard Linux hwmon prefix for fan tachometer sensors (`fan[1-*]_input`).
 * Units: Rotations Per Minute (RPM).
 */
internal const val HWMON_FAN_PREFIX = "fan"

/**
 * Standard Linux hwmon prefix for power consumption sensors (`power[1-*]_input`).
 * Units: Micro-watts (µW) in the kernel; converted to Watts by dividing by 1,000,000.
 */
internal const val HWMON_POWER_PREFIX = "power"

/**
 * Standard Linux hwmon prefix for voltage sensors (`in[0-*]_input`).
 * Units: Millivolts (mV) in the kernel; converted to Volts by dividing by 1,000.
 */
internal const val HWMON_IN_PREFIX = "in"

/**
 * Standard Linux hwmon prefix for electric current sensors (`curr[1-*]_input`).
 * Units: Milliamperes (mA) in the kernel; converted to Amperes by dividing by 1,000.
 */
internal const val HWMON_CURR_PREFIX = "curr"

/**
 * Standard Linux hwmon prefix for PWM (Pulse Width Modulation) duty cycle controls (`pwm[1-*]`).
 * Units: Raw integer 0 to 255 (0 = 0%, 255 = 100%).
 */
internal const val HWMON_PWM_PREFIX = "pwm"

/**
 * Standard Linux hwmon prefix for temperature sensors (`temp[1-*]_input`).
 * Units: Millidegrees Celsius (m°C) in the kernel; converted to °C by dividing by 1,000.
 */
internal const val HWMON_TEMP_PREFIX = "temp"

/**
 * Standard Linux hwmon suffix for read-only sensor input values.
 */
internal const val HWMON_INPUT_SUFFIX = "_input"

/**
 * For Aquacomputer devices equipped with a coolant flow sensor (e.g. High Flow NEXT, D5 NEXT),
 * the kernel driver exposes the flow rate pulses mapped to fan channel 5 (`fan5_input`).
 * Units: Deciliters per hour (dL/h).
 */
internal const val HWMON_FLOW_SENSOR_FILE = "fan5_input"

// -----------------------------------------------------------------------------
// Protocol Status
// -----------------------------------------------------------------------------

/**
 * Status string returned upon a successful operation (e.g. flashing a curve).
 */
internal const val STATUS_OK = "ok"

// -----------------------------------------------------------------------------
// Path Builder Helpers
// -----------------------------------------------------------------------------

/**
 * Builds the sysfs path to the device's `uevent` file for a given hidraw entry.
 * Example: `/sys/class/hidraw/hidraw9/device/uevent`
 */
internal fun hidrawUeventPath(entry: String): String = "$SYSFS_HIDRAW_DIR/$entry/$DEVICE_UEVENT"

/**
 * Builds the sysfs path to the hwmon subdirectory for a given hidraw entry.
 * Example: `/sys/class/hidraw/hidraw9/device/hwmon`
 */
internal fun hidrawHwmonSubdir(entry: String): String = "$SYSFS_HIDRAW_DIR/$entry/$DEVICE_HWMON"

/**
 * Builds the character device node path in `/dev` for a given hidraw entry.
 * Example: `/dev/hidraw9`
 */
internal fun hidrawDevPath(entry: String): String = "$DEV_DIR/$entry"
